    final Map<String, dynamic> jsonMap = jsonDecode(content);
    if (!jsonMap.containsKey('dns')) {
      jsonMap['dns'] = <String, dynamic>{};
    }
    final Map<String, dynamic> dnsMap = jsonMap['dns'] as Map<String, dynamic>;

    for (final k in entry.value.entries) {
      dnsMap[k.key] = k.value;
    }

    const encoder = JsonEncoder.withIndent('  ');
    file.writeAsStringSync(encoder.convert(jsonMap));
